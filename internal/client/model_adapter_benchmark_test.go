// ---------------------------------------------------------------------------
// Test case 3: detectUpstreamModelNotFoundError with error patterns
// ---------------------------------------------------------------------------

func TestDetectUpstreamModelNotFoundError_ErrorPatterns(t *testing.T) {
	tests := []struct {
		name      string
		input     string
		wantMatch bool
	}{
		{"model not found", "model gpt-999 not found", true},
		{"unknown model", "unknown model: fake-model", true},
		{"does not exist", "The model deepseek-v9 does not exist", true},
		{"invalid model", "Error: invalid model specified", true},
		{"model_not_found snake", "Error: model_not_found", true},
		{"model unavailable", "model claude-5 is currently unavailable", true},
		{"no model found", "no model matching 'x' found", true},
		{"Chinese model not found", "模型不存在", true},
		{"Chinese unsupported model", "不支持的模型", true},
		{"Chinese not found variant", "模型未找到", true},
		{"long legitimate response (501 chars)", strings.Repeat("The quick brown fox jumps over the lazy dog. ", 11) + "x", false},
		{"normal response", "Hello, this is a normal response from GPT-4.", false},
		{"short normal", "1 2 3 4 5", false},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			_, got := detectUpstreamModelNotFoundError(tt.input)
			if got != tt.wantMatch {
				t.Errorf("detectUpstreamModelNotFoundError(%q) match = %v, want %v", tt.input, got, tt.wantMatch)
			}
		})
	}
}

