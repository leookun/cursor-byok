// ---------------------------------------------------------------------------
// Test case 4: adapterExistsInConfig with real config data
// ---------------------------------------------------------------------------

func TestAdapterExistsInConfig_WithStore(t *testing.T) {
	tmpDir := t.TempDir()
	cfgPath := filepath.Join(tmpDir, "config.yaml")
	cfg := serverconfig.DefaultConfig()
	cfg.ModelAdapters = []serverconfig.ModelAdapterConfig{
		{
			ID:          "test-adapter",
			Type:        "openai",
			DisplayName: "Test Adapter",
			BaseURL:     "https://api.openai.com",
			APIKey:      "test-key",
			TooltipData: "Test OpenAI Adapter",
			ModelID:     "gpt-4",
		},
	}
	store := serverconfig.NewStore(cfgPath, tmpDir)
	_, err := store.Save(context.Background(), cfg)
	if err != nil {
		t.Fatalf("failed to save test config: %v", err)
	}

	s := &ProxyService{store: store}

	// The store's config has one adapter with ID generated by normalization.
	// Load the normalized config to find the actual ID.
	loaded, err := store.Load(context.Background())
	if err != nil {
		t.Fatalf("failed to load config: %v", err)
	}
	if len(loaded.ModelAdapters) == 0 {
		t.Fatal("expected at least one adapter after normalization")
	}
	knownID := loaded.ModelAdapters[0].ID

	// Existing adapter ID should return true
	if !s.adapterExistsInConfig(knownID, "gpt-4") {
		t.Errorf("expected true for existing adapter ID %q", knownID)
	}

	// Existing ModelID should return true via fallback (different adapterID)
	if !s.adapterExistsInConfig("nonexistent-id", "gpt-4") {
		t.Error("expected true for existing ModelID fallback")
	}

	// Non-existent adapter and model should return false
	if s.adapterExistsInConfig("nonexistent-id", "nonexistent-model") {
		t.Error("expected false for non-existent adapter and model")
	}
}

// ---------------------------------------------------------------------------
// Test case 1: TestModelAdapter with non-existent adapter returns error status
// ---------------------------------------------------------------------------

func TestTestModelAdapter_NonExistentAdapter(t *testing.T) {
	// Create a ProxyService with a store that has NO adapters configured.
	tmpDir := t.TempDir()
	cfgPath := filepath.Join(tmpDir, "config.yaml")
	cfg := serverconfig.DefaultConfig()
	cfg.ModelAdapters = nil // no adapters

	store := serverconfig.NewStore(cfgPath, tmpDir)
	_, err := store.Save(context.Background(), cfg)
	if err != nil {
		t.Fatalf("failed to save test config: %v", err)
	}

	s := &ProxyService{
		store:            store,
		modelTestResults: make(map[string]ModelAdapterTestResult),
	}

	// Construct an adapter that passes normalization (all required fields filled)
	// but does NOT match any adapter in the empty config.
	adapter := serverconfig.ModelAdapterConfig{
		Type:                        "openai",
		DisplayName:                 "Fake Adapter",
		BaseURL:                     "https://api.openai.com",
		APIKey:                      "sk-fake-test-key-12345",
		TooltipData:                 "Fake adapter for testing",
		ModelID:                     "gpt-999-nonexistent",
		ReasoningEffort:             "medium",
		OpenAIEndpoint:              "/v1/chat/completions",
	}

	result, err := s.TestModelAdapter(adapter)
	if err != nil {
		// The existence check failure returns nil error (not a Go error),
		// so if we get an err here it means normalization failed or something else.
		// Log it but don't assert on it.
		t.Logf("TestModelAdapter returned non-nil error: %v", err)
	}
	if result.Status != string(ModelAdapterTestStatusError) {
		t.Errorf("expected Status=%q, got %q", ModelAdapterTestStatusError, result.Status)
	}
	if result.Error == "" {
		t.Error("expected non-empty Error message for non-existent adapter")
	}
}